import assert from 'node:assert/strict';
import {RailwayMusic} from '../dist/music.js';
let contexts=0,fetches=0,starts=0,volume;
const context={currentTime:0,destination:{},resume:async()=>{},suspend:async()=>{},close(){},decodeAudioData:async()=>({duration:53.333333}),createGain:()=>({gain:{value:0,cancelScheduledValues(){},setValueAtTime(){},linearRampToValueAtTime(v){volume=v;}},connect(){}}),createBufferSource:()=>({connect(){},start(){starts++;},stop(){}})};
const music=new RailwayMusic({createContext:()=>{contexts++;return context;},fetchAudio:async()=>{fetches++;return {ok:true,arrayBuffer:async()=>new ArrayBuffer(4)};}});
assert.equal((await music.setEnabled(true)).needsGesture,true);
assert.equal(contexts,0);assert.equal(fetches,0);
await music.setEnabled(true,{gesture:true});
assert.equal(starts,1);assert.equal(music.source.loop,true);assert.equal(volume,.25*.65);
music.setVolume(.6);assert.equal(volume,.6*.65);
await music.setEnabled(false);assert.equal(volume,0);
await music.setEnabled(true,{gesture:true});assert.equal(starts,1);assert.equal(fetches,1);
assert.throws(()=>music.setVolume(2));
let finish;const pending=new RailwayMusic({createContext:()=>context,fetchAudio:()=>new Promise(r=>{finish=r;})});
const loading=pending.setEnabled(true,{gesture:true});await pending.setEnabled(false);
finish({ok:true,arrayBuffer:async()=>new ArrayBuffer(4)});await loading;
assert.equal(pending.enabled,false);assert.equal(volume,0);
const failed=new RailwayMusic({createContext:()=>context,fetchAudio:async()=>({ok:false})});
await failed.setEnabled(true,{gesture:true});assert.equal(failed.enabled,false);assert.equal(failed.error,true);
console.log('Music: gesture gate, looping, volume, mute/unmute, pending-load cancellation and load errors passed.');
